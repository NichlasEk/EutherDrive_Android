        _currentPos = pos;
        _currentLimit = limit;
        _cbrParamIndex = atbl;
        int sync = GetBits(ref _currentPos, 12);

    RetrySync:
        while (sync != 0xfff && _currentPos < limit)
            sync = ((sync << 1) | GetBits(ref _currentPos, 1)) & 0xfff;

        if (limit - _currentPos < 4)
            return false;

        int layer = 0;
        int variant = Gb(3);
        switch (variant)
        {
            case 2:
            case 6:
                if ((_accepted & AMM) != 0)
                    layer = 4;
                break;
        }

        if (layer == 0)
        {
            _currentPos -= 3;
            sync = ((sync << 1) | GetBits(ref _currentPos, 1)) & 0xfff;
            goto RetrySync;
        }

        try
        {
            ReadHeaderAmm(variant == 2);
            ReadDataMpeg2();
            if (_lastFrameNumber != 0)
                DecodeMpeg2(output, ref outputSamples);
            else
                outputSamples = 0;
        }
        catch (LimitHitException)
        {
            return false;
        }

        if (_positionAlign != 0)
            _currentPos = (_currentPos + _positionAlign) & ~_positionAlign;

        pos = _currentPos;
        sampleRate = SampleRates[_samplingRate];
        channels = _channelCount;
        return true;
    }

    private void ReadHeaderAmm(bool layer25)
    {
        int ammsl = Gb(1);
        int fullPacketsCount = Gb(4);
        int srateIndex = Gb(2);
        _samplingRate = srateIndex + 4 * (layer25 ? 1 : 0);
        int lastPacketFrameId = Gb(2);
        int stereoMode = Gb(2);
        int stereoModeExt = Gb(2);
        if (ammsl != 0)
        {
            _lastFrameNumber = 36;
            _paramIndex = _cbrParamIndex;
            Gb(3);
        }
        else
        {
            _lastFrameNumber = 3 * fullPacketsCount + lastPacketFrameId;
            _paramIndex = Gb(3);
        }
        Gb(1);

        _channelCount = stereoMode != 3 ? 2 : 1;
        _totalBands = TotalBandCounts[_paramIndex];
        _jointBands = _totalBands;
        if (stereoMode == 1)
            _jointBands = JointBandCounts[stereoModeExt];
        if (_jointBands > _totalBands)
            _jointBands = _totalBands;
    }

    private void ReadDataMpeg2()
    {
        ReadBandParams();
        ReadScfci();
        ReadBandAmplitudeParams();
    }

    private void DecodeMpeg2(short[] output, ref int outputSamples)
    {
        outputSamples = 0;
        BuildAmplitudes();

        int frameNumber = 0;
        int outputIndex = 0;
        double[] resynthesisBuffer = new double[32];
        for (int upperStep = 0; upperStep < 3; upperStep++)
        {
            for (int middleStep = 0; middleStep < 4; middleStep++)
            {
                BuildNextSegments(upperStep);
                for (int lowerStep = 0; lowerStep < 3; lowerStep++)
                {
                    RetrieveSubbuffer(lowerStep);
                    for (int chan = 0; chan < _channelCount; chan++)
                    {
                        Idct32(chan);
                        Resynthesis(_audioBuffer[chan], _audioBufferPos[chan] + 16, resynthesisBuffer);
                        ScaleAndClamp(resynthesisBuffer, output, outputIndex + chan, _channelCount);
                        _audioBufferPos[chan] -= 32;
                        if (_audioBufferPos[chan] < 0)
                        {
                            Array.Copy(_audioBuffer[chan], 0, _audioBuffer[chan], 17 * 32, 15 * 32);
                            _audioBufferPos[chan] = 16 * 32;
                        }
                    }
                    outputIndex += 32 * _channelCount;
                    outputSamples += 32;
                    frameNumber++;
                    if (frameNumber == _lastFrameNumber)
                        return;
                }
            }
        }
    }

    private int GetBandParam(int band)
    {
        int bitCount = BandParameterIndexBitsCount[_paramIndex, band];
        int index = Gb(bitCount);
        return BandParameterIndexedValues[_paramIndex, band, index];
    }

    private void ReadBandParams()
    {
        int band = 0;
        while (band < _jointBands)
        {
            for (int chan = 0; chan < _channelCount; chan++)
                _bandParam[chan, band] = GetBandParam(band);
            band++;
        }

        while (band < _totalBands)
        {
            int val = GetBandParam(band);
            _bandParam[0, band] = val;
            _bandParam[1, band] = val;
            band++;
        }

        while (band < 32)
        {
            _bandParam[0, band] = 0;
            _bandParam[1, band] = 0;
            band++;
        }
    }

    private void ReadScfci()
    {
        Array.Clear(_scfsi);
        for (int band = 0; band < _totalBands; band++)
            for (int chan = 0; chan < _channelCount; chan++)
                if (_bandParam[chan, band] != 0)
                    _scfsi[chan, band] = Gb(2);
    }

    private void ReadBandAmplitudeParams()
    {
        Array.Clear(_scf);
        for (int band = 0; band < _totalBands; band++)
        {
            for (int chan = 0; chan < _channelCount; chan++)
            {
                if (_bandParam[chan, band] == 0)
                    continue;

                switch (_scfsi[chan, band])
                {
                    case 0:
                        _scf[chan, 0, band] = Gb(6);
                        _scf[chan, 1, band] = Gb(6);
                        _scf[chan, 2, band] = Gb(6);
                        break;
                    case 1:
                    {
                        int val = Gb(6);
                        _scf[chan, 0, band] = val;
                        _scf[chan, 1, band] = val;
                        _scf[chan, 2, band] = Gb(6);
                        break;
                    }
                    case 2:
                    {
                        int val = Gb(6);
                        _scf[chan, 0, band] = val;
                        _scf[chan, 1, band] = val;
                        _scf[chan, 2, band] = val;
                        break;
                    }
                    case 3:
                    {
                        _scf[chan, 0, band] = Gb(6);
                        int val = Gb(6);
                        _scf[chan, 1, band] = val;
                        _scf[chan, 2, band] = val;
                        break;
                    }
                }
            }
        }
    }

    private void BuildAmplitudes()
    {
        Array.Clear(_ampValues);
        for (int band = 0; band < _totalBands; band++)
            for (int chan = 0; chan < _channelCount; chan++)
                if (_bandParam[chan, band] != 0)
                    for (int step = 0; step < 3; step++)
                        _ampValues[chan, step, band] = ScaleFactors[_scf[chan, step, band]];
    }

    private void ReadBandValueTriplet(int chan, int band)
    {
        Span<double> buffer = stackalloc double[3];
        int bandIdx = _bandParam[chan, band];
        switch (bandIdx)
        {
            case 0:
                _bdata[chan, 0, band] = 0;
                _bdata[chan, 1, band] = 0;
                _bdata[chan, 2, band] = 0;
                return;
            case 1:
            case 2:
            case 4:
            {
                int modulo = BandInfos[bandIdx].Modulo;
                int val = Gb(BandInfos[bandIdx].CubeBits);
                buffer[0] = val % modulo;
                val /= modulo;
                buffer[1] = val % modulo;
                val /= modulo;
                buffer[2] = val % modulo;
                break;
            }
            default:
            {
                int bits = BandInfos[bandIdx].Bits;
                buffer[0] = Gb(bits);
                buffer[1] = Gb(bits);
                buffer[2] = Gb(bits);
                break;
            }
        }

        double scale = 1 << (BandInfos[bandIdx].Bits - 1);
        _bdata[chan, 0, band] = ((buffer[0] - scale) / scale + BandInfos[bandIdx].Offset) * BandInfos[bandIdx].Scale;
        _bdata[chan, 1, band] = ((buffer[1] - scale) / scale + BandInfos[bandIdx].Offset) * BandInfos[bandIdx].Scale;
        _bdata[chan, 2, band] = ((buffer[2] - scale) / scale + BandInfos[bandIdx].Offset) * BandInfos[bandIdx].Scale;
    }

    private void BuildNextSegments(int step)
    {
        int band = 0;
        while (band < _jointBands)
        {
            for (int chan = 0; chan < _channelCount; chan++)
            {
                ReadBandValueTriplet(chan, band);
                double amp = _ampValues[chan, step, band];
                _bdata[chan, 0, band] *= amp;
                _bdata[chan, 1, band] *= amp;
                _bdata[chan, 2, band] *= amp;
            }
            band++;
        }

        while (band < _jointBands)
        {
            ReadBandValueTriplet(0, band);
            _bdata[1, 0, band] = _bdata[0, 0, band];
            _bdata[1, 1, band] = _bdata[0, 1, band];
            _bdata[1, 2, band] = _bdata[0, 2, band];
            for (int chan = 0; chan < _channelCount; chan++)
            {
                double amp = _ampValues[chan, step, band];
                _bdata[chan, 0, band] *= amp;
                _bdata[chan, 1, band] *= amp;
                _bdata[chan, 2, band] *= amp;
            }
            band++;
        }

        while (band < 32)
        {
            _bdata[0, 0, band] = 0;
            _bdata[0, 1, band] = 0;
            _bdata[0, 2, band] = 0;
            _bdata[1, 0, band] = 0;
            _bdata[1, 1, band] = 0;
            _bdata[1, 2, band] = 0;
            band++;
        }
    }

    private void RetrieveSubbuffer(int step)
    {
        for (int chan = 0; chan < _channelCount; chan++)
            for (int i = 0; i < 32; i++)
                _subbuffer[chan, i] = _bdata[chan, step, i];
    }

    private void Idct32(int chan)
    {
        int outputOffset = _audioBufferPos[chan];
        for (int i = 0; i < 32; i++)
        {
            double s = 0;
            for (int j = 0; j < 32; j++)
                s += _subbuffer[chan, j] * _cosCache[i, j];
            _audioBuffer[chan][outputOffset + i] = s;
        }
    }

    private static void Resynthesis(double[] input, int inputOffset, double[] output)
    {
        Array.Clear(output);
        for (int j = 0; j < 64 * 8; j += 64)
        {
            for (int i = 0; i < 16; i++)
                output[i] += input[inputOffset + i + j] * SynthesisFilter[i + j] - input[inputOffset + 32 - i + j] * SynthesisFilter[32 + i + j];
            output[16] -= input[inputOffset + 16 + j] * SynthesisFilter[32 + 16 + j];
            for (int i = 17; i < 32; i++)
                output[i] -= input[inputOffset + 32 - i + j] * SynthesisFilter[i + j] + input[inputOffset + i + j] * SynthesisFilter[32 + i + j];
        }
    }

    private static void ScaleAndClamp(double[] input, short[] output, int outputIndex, int step)
    {
        for (int i = 0; i < 32; i++)
        {
            double val = input[i] * 32768 + 0.5;
            short cval;
            if (val <= -32768)
                cval = -32768;
            else if (val >= 32767)
                cval = 32767;
            else
                cval = (short)(int)val;
            output[outputIndex] = cval;
            outputIndex += step;
        }
    }

    private int Gb(int count)
    {
        if (_currentPos + count > _currentLimit)
            throw new LimitHitException();
        return GetBits(ref _currentPos, count);
    }

    private int GetBits(int pos, int count)
    {
        return GetBits(ref pos, count);
    }

    private int GetBits(ref int pos, int count)
    {
        int v = 0;
        for (int i = 0; i != count; i++)
        {
            v <<= 1;
            int byteIndex = pos >> 3;
            if (byteIndex >= _base.Length)
                throw new LimitHitException();
            int mask = _lsbFirst ? (0x01 << (pos & 7)) : (0x80 >> (pos & 7));
            if ((_base[byteIndex] & mask) != 0)
                v |= 1;
            pos++;
        }
        return v;
    }

    private readonly struct BandInfo
    {
        public BandInfo(int modulo, double s1, int bits, int cubeBits, int s4, int s5, double range, double s7, double scale, double offset)
        {
            Modulo = modulo;
            Bits = bits;
            CubeBits = cubeBits;
            Scale = scale;
            Offset = offset;
        }

        public int Modulo { get; }
        public int Bits { get; }
        public int CubeBits { get; }
        public double Scale { get; }
        public double Offset { get; }
    }

    private sealed class LimitHitException : Exception
    {
    }
}
